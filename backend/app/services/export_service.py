import json
import yaml
from typing import Dict, Any
from ..schemas.models import AnalysisResult

class ExportService:
    @staticmethod
    def generate_markdown_report(result: AnalysisResult) -> str:
        """Produces a comprehensive, evidence-linked reproduction report."""
        meta = result.metadata
        ov = result.overview

        lines = [
            f"# Paper2Run Reproduction Blueprint & Evidence Report",
            f"",
            f"**Paper:** {meta.title}  ",
            f"**Source File:** `{meta.filename}` ({meta.page_count} pages)  ",
            f"**Analysis Date:** {meta.created_at}  ",
            f"**Mode:** {'Sample Demo Baseline' if meta.is_sample_demo else 'Verified Live Analysis'}  ",
            f"**Readiness Score:** {meta.reported_fields}/{meta.total_fields} fields reported ({meta.unresolved_gaps} unresolved reproduction gaps)  ",
            f"",
            f"---",
            f"",
            f"## 1. Executive Research Overview",
            f"",
            f"### Problem & Objective",
            f"{ov.research_problem}",
            f"",
            f"### Proposed Method & Motivation",
            f"{ov.motivation_and_method}",
            f"",
            f"### Main Model Architecture",
            f"{ov.main_architecture}",
            f"",
            f"### Key Results",
            f"{ov.main_results}",
            f"",
            f"### Limitations & Open Questions",
            f"{ov.limitations_and_questions}",
            f"",
            f"---",
            f"",
            f"## 2. Structured Experiment Blueprint (Evidence-Backed)",
            f"",
            f"| Category | Field Name | Extracted Value | Status | Source Evidence |",
            f"| :--- | :--- | :--- | :--- | :--- |"
        ]

        for field in result.blueprint:
            val_display = field.value if field.value is not None else "_UNKNOWN / NOT REPORTED_"
            status_badge = field.status.upper().replace("_", " ")
            ev_snippets = []
            for ev in field.evidence:
                ev_str = f"Page {ev.page_index + 1} ({ev.section}): \"{ev.quote[:100]}...\""
                ev_snippets.append(ev_str)
            ev_display = "<br>".join(ev_snippets) if ev_snippets else "_No direct citation found_"
            lines.append(f"| {field.category.capitalize()} | **{field.name}** | {val_display} | `{status_badge}` | {ev_display} |")

        lines.extend([
            f"",
            f"---",
            f"",
            f"## 3. Unresolved Reproduction Gaps & Action Checklist",
            f""
        ])

        if not result.gaps:
            lines.append("_No critical reproduction gaps detected in examined sections._\n")
        else:
            for idx, gap in enumerate(result.gaps, 1):
                lines.extend([
                    f"### Gap {idx}: {gap.field_name} (`{gap.status.upper()}`)",
                    f"- **Category:** {gap.category}",
                    f"- **What is Missing/Ambiguous:** {gap.missing_explanation}",
                    f"- **Why it Matters:** {gap.why_it_matters}",
                    f"- **Examined Sections:** {', '.join(gap.examined_sections)}",
                    f"- **Suggested Candidate Setting (Suggestion Only):** `{gap.suggested_candidate_value or 'None'}`",
                    f"  - _Rationale:_ {gap.candidate_rationale or 'N/A'}",
                    f"  - _Source:_ {gap.candidate_source or 'N/A'}",
                    f"- **Next-Step Investigation Checklist:**"
                ])
                for act in gap.recommended_actions:
                    lines.append(f"  - [ ] {act}")
                lines.append("")

        lines.extend([
            f"---",
            f"",
            f"## 4. Honest Reproduction Boundaries",
            f"- This blueprint organizes reported evidence and highlights unknown parameters.",
            f"- It does not guarantee exact reproduction, as environmental variation, seed variance, and hardware FLOP precision can alter training dynamics.",
            f"- Generated by Paper2Run."
        ])

        return "\n".join(lines)

    @staticmethod
    def generate_json_blueprint(result: AnalysisResult) -> str:
        """Returns JSON representation preserving nulls for unknown fields."""
        data = result.model_dump()
        return json.dumps(data, indent=2)

    @staticmethod
    def generate_yaml_blueprint(result: AnalysisResult) -> str:
        """Returns YAML representation preserving nulls for unknown fields."""
        data = result.model_dump()
        return yaml.dump(data, sort_keys=False, default_flow_style=False)

    @staticmethod
    def generate_checklist_markdown(result: AnalysisResult) -> str:
        """Generates an actionable reproduction checklist."""
        lines = [
            f"# Reproduction Checklist for {result.metadata.title}",
            f"",
            f"Use this checklist to track your setup, validation, and training steps.",
            f"",
            f"## Phase 1: Environment & Dataset Preparation"
        ]

        dataset_field = next((f for f in result.blueprint if f.category == "dataset"), None)
        if dataset_field and dataset_field.value:
            lines.append(f"- [ ] Download and verify dataset: {dataset_field.value}")
        else:
            lines.append("- [ ] Investigate dataset location and download script")

        prep_field = next((f for f in result.blueprint if f.category == "preprocessing"), None)
        if prep_field and prep_field.value:
            lines.append(f"- [ ] Implement tokenization/preprocessing pipeline: {prep_field.value}")

        lines.extend([
            f"",
            f"## Phase 2: Model Architecture & Initialization"
        ])
        arch_field = next((f for f in result.blueprint if f.category == "model_architecture"), None)
        if arch_field and arch_field.value:
            lines.append(f"- [ ] Instantiate model architecture: {arch_field.value}")

        init_gap = next((g for g in result.gaps if "init" in g.field_id.lower()), None)
        if init_gap:
            lines.append(f"- [ ] **RESOLVE GAP:** {init_gap.field_name}. Suggested choice: {init_gap.suggested_candidate_value}")

        lines.extend([
            f"",
            f"## Phase 3: Optimizer & Hyperparameters"
        ])
        for cat in ["optimizer", "learning_rate_schedule", "loss", "training_setup"]:
            for f in result.blueprint:
                if f.category == cat:
                    status_text = f"(`{f.status}`)"
                    val = f.value if f.value else "UNKNOWN - MUST CONFIGURE"
                    lines.append(f"- [ ] Set {f.name}: {val} {status_text}")

        lines.extend([
            f"",
            f"## Phase 4: Gaps & Investigation Items"
        ])
        for g in result.gaps:
            lines.append(f"- [ ] **[CRITICAL GAP]** {g.field_name}: {g.missing_explanation[:100]}...")
            for act in g.recommended_actions:
                lines.append(f"    - [ ] {act}")

        return "\n".join(lines)
